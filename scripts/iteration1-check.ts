import '../packages/shared/src/env.js';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { deployment } from '../packages/shared/src/local.js';
import { confirmPayment } from '../packages/shared/src/receipt.js';
import { publicData, type ExperimentEvent } from '../packages/experiment/src/events.js';
const file = process.argv[2] ?? 'evidence/iteration-1-result.json';
const run = JSON.parse(fs.readFileSync(file, 'utf8'));
assert.equal(run.status, 'completed', 'The run must have completed');
assert.equal(run.mode, 'live-llm', 'Controlled tests are not evidence of a live LLM experiment');
assert.ok(run.models.agent1 && run.models.agent2, 'Both model IDs are required');
assert.ok(run.messageId && run.taskId && run.transaction && run.assessment && run.output && run.provenance, 'Incomplete evidence');
const events: ExperimentEvent[] = fs.readdirSync('runtime/events').filter(f=>f.endsWith('.jsonl')).flatMap(f=>fs.readFileSync(`runtime/events/${f}`,'utf8').split('\n').flatMap(line=>{try{return [JSON.parse(line)];}catch{return [];}})).filter(e=>e.runId===run.id||e.messageId===run.messageId);
const auth = events.find(e=>e.type==='authorization-created')!;
assert.ok(auth?.data.nonce && auth.data.payer, 'Authorization summary missing');
const receipt = await confirmPayment(deployment(), run.receipt, String(auth.data.payer), String(auth.data.nonce));
assert.equal(receipt.transaction, run.transaction);
const phases = events.filter(e=>e.source==='agent2').sort((a,b)=>a.sequence-b.sequence).map(e=>e.type);
let previous=-1;
for(const phase of ['verified','executing','output-validated','execution-succeeded','settling','settlement-pending','settled','delivered']) {const index=phases.indexOf(phase);assert.ok(index>previous,`Missing or out-of-order phase ${phase}`);previous=index;}
assert.equal(events.filter(e=>e.type==='authorization-created').length,1);
assert.equal(events.filter(e=>e.type==='paid-retry').length,1);
assert.ok(events.some(e=>e.type==='task-poll'&&e.data.method==='GetTask'));
assert.ok(events.filter(e=>e.source==='agent1'&&e.type==='model-end').length>=6);
assert.equal(events.filter(e=>e.source==='agent2'&&e.type==='model-end').length,1);
assert.equal(BigInt(run.before.client)-BigInt(run.after.client),2_000_000n);
assert.equal(BigInt(run.after.card)-BigInt(run.before.card),2_000_000n);
const evidence=publicData({...run,receipt,events,verifiedAt:new Date().toISOString(),checks:{realLLMs:true,discovery:true,singleAuthorization:true,taskPolling:true,executionBeforeSettlement:true,confirmedTransfer:true,amount:'2000000'}});
fs.writeFileSync(`evidence/${run.id}-verified.json`,JSON.stringify(evidence,null,2)+'\n',{mode:0o600});
fs.writeFileSync(file,JSON.stringify(evidence,null,2)+'\n',{mode:0o600});
console.log(JSON.stringify({passed:true,runId:run.id,transaction:run.transaction,eventCount:events.length,mode:run.mode},null,2));
